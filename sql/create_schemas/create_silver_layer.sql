CREATE TABLE IF NOT EXISTS silver_crypto_market_snapshots (
    run_id                            BIGINT NOT NULL REFERENCES pipeline_runs(run_id),
    coin_id                           TEXT NOT NULL,
    symbol                            TEXT NOT NULL,
    name                              TEXT,
    current_price                     NUMERIC,
    market_cap                        NUMERIC,
    market_cap_rank                   INT,
    fully_diluted_valuation           NUMERIC,
    total_volume                      NUMERIC,
    high_24h                          NUMERIC,
    low_24h                           NUMERIC,
    price_change_24h                  NUMERIC,
    price_change_percentage_24h       NUMERIC,
    market_cap_change_24h             NUMERIC,
    market_cap_change_percentage_24h  NUMERIC,
    circulating_supply                NUMERIC,
    total_supply                      NUMERIC,
    max_supply                        NUMERIC,
    ath                               NUMERIC,
    ath_change_percentage             NUMERIC,
    ath_date                          TIMESTAMPTZ,
    atl                               NUMERIC,
    atl_change_percentage             NUMERIC,
    atl_date                          TIMESTAMPTZ,
    last_updated                      TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (run_id, coin_id)
);